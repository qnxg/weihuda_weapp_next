export type Audience = "male" | "female";
export type GradeGroup = "lower" | "upper";
export type StandardProjectId =
  "bmi" | "vital-capacity" | "sprint" | "sit-reach" | "standing-jump" | "strength" | "endurance";
export type StandardRowKind = "standard" | "bonus";
export type BmiCategory = "正常" | "低体重" | "超重" | "肥胖";

export interface StandardRow {
  kind: StandardRowKind;
  score: number;
  thresholds: readonly [lower: string, upper: string];
  category?: BmiCategory;
}

export interface StandardProject {
  id: StandardProjectId;
  shortName: string | Readonly<Record<Audience, string>>;
  name: string | Readonly<Record<Audience, string>>;
  weight: number;
  unit: string;
  standards: Readonly<Record<Audience, readonly StandardRow[]>>;
}


function directionalRows(
  scores: readonly number[],
  lower: readonly string[],
  upper: readonly string[],
  symbol: "≥" | "≤",
): readonly StandardRow[] {
  if (scores.length !== lower.length || scores.length !== upper.length) {
    throw new Error("体测标准的分值与成绩要求数量不一致");
  }

  return scores.map((score, index) => ({
    kind: "standard",
    score,
    thresholds: [`${symbol} ${lower[index]}`, `${symbol} ${upper[index]}`],
  }));
}

function bonusRows(
  lower: readonly string[],
  upper: readonly string[],
  symbol: "≥" | "≤",
): readonly StandardRow[] {
  if (bonusScores.length !== lower.length || bonusScores.length !== upper.length) {
    throw new Error("体测附加分与成绩要求数量不一致");
  }

  return bonusScores.map((score, index) => ({
    kind: "bonus",
    score,
    thresholds: [`${symbol} ${lower[index]}`, `${symbol} ${upper[index]}`],
  }));
}

function bmiRows(normal: string, lowWeight: string): readonly StandardRow[] {
  return [
    {
      category: "正常",
      kind: "standard",
      score: 100,
      thresholds: [normal, normal],
    },
    {
      category: "低体重",
      kind: "standard",
      score: 80,
      thresholds: [`≤ ${lowWeight}`, `≤ ${lowWeight}`],
    },
    {
      category: "超重",
      kind: "standard",
      score: 80,
      thresholds: ["24.0–27.9", "24.0–27.9"],
    },
    {
      category: "肥胖",
      kind: "standard",
      score: 60,
      thresholds: ["≥ 28.0", "≥ 28.0"],
    },
  ];
}

